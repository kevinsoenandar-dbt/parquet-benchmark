"""
Uploads the 2 Ab Initio parquet files (generated by
generate_abinitio_from_dbt_export.py) to a Snowflake internal stage. The
dbt-side files are NOT uploaded by this script — they're produced directly
on stage by `dbt run-operation export_benchmark_dbt_tables`, since that's
what a real dbt-exported parquet actually is.

Creates the stage `benchmark_stage` if it doesn't exist, then PUTs the
abinitio_*.parquet files under dummy_data/ into @benchmark_stage/benchmark/.
AUTO_COMPRESS is disabled since parquet is already compressed.

Credentials are read from environment variables only — nothing is
hardcoded or requested interactively by this script:
    SNOWFLAKE_ACCOUNT
    SNOWFLAKE_USERNAME
    SNOWFLAKE_PASSWORD      (omit if using SNOWFLAKE_AUTHENTICATOR=externalbrowser)
    SNOWFLAKE_AUTHENTICATOR (optional, e.g. 'externalbrowser' for SSO)
    SNOWFLAKE_ROLE
    SNOWFLAKE_WAREHOUSE
    SNOWFLAKE_DB
    SNOWFLAKE_SCHEMA

Run: python upload_to_stage.py [--data-dir ../dummy_data]
"""
import argparse
import glob
import os
import sys

import snowflake.connector


def get_connection():
    required = ["SNOWFLAKE_ACCOUNT", "SNOWFLAKE_USERNAME", "SNOWFLAKE_WAREHOUSE",
                "SNOWFLAKE_DB", "SNOWFLAKE_SCHEMA"]
    missing = [v for v in required if not os.environ.get(v)]
    if missing:
        sys.exit(f"Missing required env vars: {', '.join(missing)}")

    kwargs = dict(
        account=os.environ["SNOWFLAKE_ACCOUNT"],
        user=os.environ["SNOWFLAKE_USERNAME"],
        warehouse=os.environ["SNOWFLAKE_WAREHOUSE"],
        database=os.environ["SNOWFLAKE_DB"],
        schema=os.environ["SNOWFLAKE_SCHEMA"],
    )
    if os.environ.get("SNOWFLAKE_ROLE"):
        kwargs["role"] = os.environ["SNOWFLAKE_ROLE"]
    if os.environ.get("SNOWFLAKE_AUTHENTICATOR"):
        kwargs["authenticator"] = os.environ["SNOWFLAKE_AUTHENTICATOR"]
    elif os.environ.get("SNOWFLAKE_PASSWORD"):
        kwargs["password"] = os.environ["SNOWFLAKE_PASSWORD"]
    else:
        sys.exit("Set either SNOWFLAKE_PASSWORD or SNOWFLAKE_AUTHENTICATOR")

    return snowflake.connector.connect(**kwargs)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", default=os.path.join(os.path.dirname(__file__), "..", "dummy_data"))
    parser.add_argument("--stage", default="benchmark_stage")
    args = parser.parse_args()

    data_dir = os.path.abspath(args.data_dir)
    files = sorted(glob.glob(os.path.join(data_dir, "abinitio_*.parquet")))
    if not files:
        sys.exit(f"No abinitio_*.parquet files found in {data_dir} — run generate_abinitio_from_dbt_export.py first")

    conn = get_connection()
    try:
        cur = conn.cursor()
        cur.execute(f"CREATE STAGE IF NOT EXISTS {args.stage}")
        for f in files:
            # The whole file:// URI must be single-quoted when the local path
            # contains spaces or special characters.
            put_sql = (
                f"PUT 'file://{f}' @{args.stage}/benchmark/ "
                "AUTO_COMPRESS=FALSE OVERWRITE=TRUE"
            )
            print(f"Uploading {os.path.basename(f)}...")
            cur.execute(put_sql)
        print(f"Done. Files staged at @{args.stage}/benchmark/")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
